CREATE TABLE IF NOT EXISTS withholds (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    code character varying(255) NOT NULL,
    number character varying(255) NOT NULL,
    date date NOT NULL,
    identification_type character varying(255) NOT NULL,
    identification character varying(255) NOT NULL,
    legal_name character varying(255) NOT NULL,
    access_key character varying(255) NOT NULL,
    fiscal_period character varying(255) NOT NULL,
    related character varying(255),
    created_at timestamp without time zone NOT NULL DEFAULT now(),
    CONSTRAINT withholds_pkey PRIMARY KEY (id)
);

CREATE UNIQUE INDEX IF NOT EXISTS ix_withholds_code_number ON withholds (code, number);
CREATE UNIQUE INDEX IF NOT EXISTS ix_withholds_access_key ON withholds (access_key);

CREATE TABLE IF NOT EXISTS withholds_support (
