CREATE VIEW v_ele_invoices AS
    select
        i.id::bigint id,
        i.code,
        i.number,
        '01' as code_document,
        substr(i.number, 1, 3) as establishment,
        substr(i.number, 4, 3) as emission_point,
        substr(i.number, 7, 15) as sequence,
        i.date,
        sum(d.total_without_tax) as total_without_taxes,
        sum(d.discount) discount,
        sum(d.total) total,
        0::numeric tip,
        i.identification_type,
        i.identification,
        i.legal_name,
        i.address,
        i.delivery_note,
        (
        select
            e.address
        from
            establishments e
        where
            e.code = substr(i.number, 1, 3)) establishment_address,
        i.access_key
    from
        documents i
    join documents_detail d
    on
        i.id = d.document_id
    group by
        i.id,
        i.code,
        i.number,
        substr(i.number, 1, 3),
        substr(i.number, 4, 3),
        substr(i.number, 7, 15),
        i.date,
        i.identification_type,
        i.identification,
        i.legal_name,
        i.address,
        i.delivery_note,
        i.access_key;

